import { useEffect, useState } from 'react';
import { getCard, getShip, type ShipResult } from '../api';
import { Markdown } from '../Markdown';
import { Seg } from '../ui';

export function ShipStep() {
  const [view, setView] = useState<'card' | 'files'>('card');
  const [md, setMd] = useState('');
  const [ship, setShip] = useState<ShipResult | null>(null);
  const [open, setOpen] = useState('serve.py');
  useEffect(() => { getCard('1').then(r => setMd(r.markdown)).catch(() => undefined); getShip().then(setShip).catch(() => undefined); }, []);
  const file = ship?.files.find(f => f.path === open);
  return (
    <div className="stack ship">
      <div className="shipbar">
        <Seg label="What to look at" value={view} onChange={setView} options={[{ value: 'card', label: 'Model card' }, { value: 'files', label: 'Ready-to-run folder' }]} />
        <p className="muted small">{view === 'card' ? 'Written from the contract. Nobody fills in a template.' : 'Generated by mt ship from the same contract.'}</p>
      </div>
      {view === 'card' ? (
        <div className="card scroll"><Markdown source={md} /></div>
      ) : (
        <div className="files">
          <ul className="flist" role="tree">
            {ship?.files.map(f => <li key={f.path}><button type="button" className={open === f.path ? 'on' : ''} onClick={() => setOpen(f.path)}>{f.path}</button></li>)}
            <li className="omit">model/ <em>not shown</em></li>
          </ul>
          <div className="card scroll"><p className="muted small">{file?.note}</p><pre className="code">{file?.content}</pre></div>
        </div>
      )}
    </div>
  );
}
